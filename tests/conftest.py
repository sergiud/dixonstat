import json
import mpmath as mp
import pathlib
import pytest

GOLDEN_TABLE = pathlib.Path(__file__).parent / 'data' / 'critical_values.json'


def _load_golden_table():
    return json.loads(GOLDEN_TABLE.read_text())


def pytest_generate_tests(metafunc):
    if 'golden_entry' in metafunc.fixturenames:
        entries = _load_golden_table()['entries']
        ids = [f"n{e['size']}-j{e['j']}-i{e['i']}-q{e['q']}" for e in entries]
        metafunc.parametrize('golden_entry', entries, ids=ids)


@pytest.fixture(scope='session')
def golden_table():
    """The golden critical values generated by scripts/reference_dixon.py."""
    return _load_golden_table()


@pytest.fixture(scope='session')
def golden_value(golden_table):
    """Return a function that looks up a stored critical value as an mpf."""
    values = {
        (e['size'], e['j'], e['i'], e['q']): e['critical_value']
        for e in golden_table['entries']
    }

    def lookup(size, j, i, q):
        with mp.workdps(golden_table['dps']):
            return mp.mpf(values[(size, j, i, q)])

    return lookup
